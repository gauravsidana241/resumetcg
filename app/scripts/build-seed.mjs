// Validates src/data/cards.json and writes supabase/seed.sql (the slim card catalogue).
// Run: npm run seed:build, then run supabase/seed.sql against the database.
import { readFileSync, writeFileSync } from 'node:fs'

const deck = JSON.parse(readFileSync(new URL('../src/data/cards.json', import.meta.url), 'utf8'))
const stackIds = new Set(deck.stacks.map((s) => s.id))
const setIds = new Set(deck.sets.map((s) => s.id))
const setOf = new Map(deck.stacks.map((s) => [s.id, s.set]))
// code blocks are not wrapped on the card, so long lines get cut off
const MAX_CODE_LINE = 42
const rarities = new Set(['common', 'rare', 'ultra'])
const types = new Set(['concept', 'story', 'tradeoff', 'trap', 'boss', 'syntax'])
const seen = new Set()
const errors = []

for (const card of deck.cards) {
  if (seen.has(card.id)) errors.push(`duplicate id ${card.id}`)
  seen.add(card.id)
  if (!stackIds.has(card.stack)) errors.push(`${card.id}: unknown stack ${card.stack}`)
  if (!rarities.has(card.rarity)) errors.push(`${card.id}: unknown rarity ${card.rarity}`)
  if (!types.has(card.type)) errors.push(`${card.id}: unknown type ${card.type}`)
  if (!card.points?.length || card.points.length > 5) errors.push(`${card.id}: needs 1-5 points`)
  for (const field of ['code', 'answer']) {
    for (const line of card[field]?.split('\n') ?? []) {
      if (line.length > MAX_CODE_LINE) errors.push(`${card.id}: ${field} line over ${MAX_CODE_LINE} chars: ${line}`)
    }
  }
}
for (const stack of deck.stacks) {
  if (!setIds.has(stack.set)) errors.push(`stack ${stack.id}: unknown set ${stack.set}`)
}
if (errors.length) {
  console.error(errors.join('\n'))
  process.exit(1)
}

const q = (s) => `'${s.replaceAll("'", "''")}'`
const rows = deck.cards
  .map((c) => `  (${q(c.id)}, ${q(c.stack)}, ${q(c.rarity)}, ${q(setOf.get(c.stack))})`)
  .join(',\n')
const ids = deck.cards.map((c) => q(c.id)).join(', ')

writeFileSync(
  new URL('../supabase/seed.sql', import.meta.url),
  `-- Generated by scripts/build-seed.mjs. Do not edit by hand.
insert into public.cards (id, stack, rarity, set_id) values
${rows}
on conflict (id) do update
  set stack = excluded.stack, rarity = excluded.rarity, set_id = excluded.set_id, active = true;

-- cards removed from the deck are retired, not deleted, so progress history survives
update public.cards set active = false where id not in (${ids});
`,
)

const count = (key) =>
  Object.entries(Object.groupBy(deck.cards, (c) => c[key])).map(([k, v]) => `${k}: ${v.length}`).join(', ')
console.log(`${deck.cards.length} cards\n  ${count('rarity')}\n  ${count('stack')}`)
for (const set of deck.sets) {
  const inSet = deck.cards.filter((c) => setOf.get(c.stack) === set.id)
  const byRarity = Object.entries(Object.groupBy(inSet, (c) => c.rarity))
  console.log(`  set ${set.id}: ${inSet.length} (${byRarity.map(([k, v]) => `${k} ${v.length}`).join(', ')})`)
}
